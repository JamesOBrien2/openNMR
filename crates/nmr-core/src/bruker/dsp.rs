/// Group delay in points; `None` if the combination is not in the table.
/// Firmware 14 and later stores the delay in `GRPDLY`, so the table gives 0.
pub(crate) fn group_delay(dspfvs: i64, decim: i64) -> Option<f64> {
    let table = match dspfvs {
        10 => DSPFVS_10,
        11 => DSPFVS_11,
        12 => DSPFVS_12,
        13 => DSPFVS_13,
        v if v >= 14 => return Some(0.0),
        _ => return None,
    };
    table.iter().find(|(d, _)| *d == decim).map(|(_, g)| *g)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn looks_up_table() {
        assert_eq!(group_delay(10, 1024), Some(70.48486328125));
        assert_eq!(group_delay(12, 16), Some(71.625));
        assert_eq!(group_delay(13, 96), Some(2.9947916666666665));
        assert_eq!(group_delay(20, 7), Some(0.0));
        assert_eq!(group_delay(13, 128), None);
        assert_eq!(group_delay(9, 2), None);
    }
}
